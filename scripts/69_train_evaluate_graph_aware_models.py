# METRICS
# ==================================================================================================

def calculate_metrics(
    y_true,
    probabilities,
    threshold,
):

    predictions = (
        probabilities >= threshold
    ).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y_true,
        predictions,
        labels=[0, 1],
    ).ravel()

    specificity = (
        tn / (tn + fp)
        if (tn + fp) > 0
        else np.nan
    )

    sensitivity = (
        tp / (tp + fn)
        if (tp + fn) > 0
        else np.nan
    )

    return {
        "threshold": float(threshold),

        "accuracy": float(
            accuracy_score(
                y_true,
                predictions,
            )
        ),

        "balanced_accuracy": float(
            balanced_accuracy_score(
                y_true,
                predictions,
            )
        ),

        "precision": float(
            precision_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),

        "recall": float(
            recall_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),

        "specificity": float(
            specificity
        ),

        "f1": float(
            f1_score(
                y_true,
                predictions,
                zero_division=0,
            )
        ),

        "mcc": float(
            matthews_corrcoef(
                y_true,
                predictions,
            )
        ),

        "roc_auc": safe_auc(
            y_true,
            probabilities,
        ),

        "pr_auc": safe_pr_auc(
            y_true,
            probabilities,
        ),

        "tn": int(tn),
        "fp": int(fp),
        "fn": int(fn),
        "tp": int(tp),
    }


# ==================================================================================================
# THRESHOLD SEARCH
# ==================================================================================================

def select_threshold(
    y_true,
    probabilities,
):

    thresholds = np.arange(
        0.05,
        0.951,
        0.01,
    )

    rows = []

    for threshold in thresholds:

        metrics = calculate_metrics(
            y_true,
            probabilities,
            threshold,
        )

        rows.append(metrics)

    result = pd.DataFrame(rows)

    # Primary objective = MCC.
    #
    # Tie-breakers:
    # 1. balanced accuracy
    # 2. F1
    # 3. threshold closest to 0.5

    result["distance_from_05"] = (
        result["threshold"] - 0.5
    ).abs()

    result = result.sort_values(
        by=[
            "mcc",
            "balanced_accuracy",
            "f1",
            "distance_from_05",
        ],
        ascending=[
            False,
            False,
            False,
            True,
        ],
    )

    best = result.iloc[0]

    return (
        float(best["threshold"]),
        result,
    )



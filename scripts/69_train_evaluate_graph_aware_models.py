def aggregate_runs(seeds):
    frames = []
    for seed in seeds:
        path = BASE_OUT / f"seed_{seed}" / "test_results.csv"
        if path.exists():
            d = pd.read_csv(path)
            d.insert(0, "seed", seed)
            frames.append(d)
    if not frames:
        raise RuntimeError("No per-seed test_results.csv files were produced.")
    all_runs = pd.concat(frames, ignore_index=True)
    all_runs.to_csv(BASE_OUT / "all_runs_test_results.csv", index=False)
    metrics = ["accuracy", "balanced_accuracy", "precision", "recall", "specificity", "f1", "mcc", "roc_auc", "pr_auc"]
    summary = all_runs.groupby(["protocol", "feature_set", "model"])[metrics].agg(["mean", "std"]).reset_index()
    summary.columns = ["_".join([str(x) for x in col if str(x)]) for col in summary.columns.to_flat_index()]
    summary.to_csv(BASE_OUT / "multi_run_summary.csv", index=False)

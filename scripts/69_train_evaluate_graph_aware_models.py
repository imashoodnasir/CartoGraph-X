def build_model(
    model_name,
    params,
):

    if model_name == "logistic_regression":

        estimator = LogisticRegression(
            C=params["C"],
            class_weight=params["class_weight"],
            solver="liblinear",
            max_iter=3000,
            random_state=SEED,
        )

        pipeline = Pipeline(
            steps=[
                (
                    "imputer",
                    SimpleImputer(
                        strategy="median",
                        add_indicator=True,
                    ),
                ),
                (
                    "scaler",
                    RobustScaler(),
                ),
                (
                    "model",
                    estimator,
                ),
            ]
        )

        return pipeline

    if model_name == "random_forest":

        estimator = RandomForestClassifier(
            n_estimators=params["n_estimators"],
            max_depth=params["max_depth"],
            min_samples_leaf=params["min_samples_leaf"],
            max_features=params["max_features"],
            class_weight=params["class_weight"],
            random_state=SEED,
            n_jobs=-1,
        )

        pipeline = Pipeline(
            steps=[
                (
                    "imputer",
                    SimpleImputer(
                        strategy="median",
                        add_indicator=True,
                    ),
                ),
                (
                    "model",
                    estimator,
                ),
            ]
        )

        return pipeline

    if model_name == "extra_trees":

        estimator = ExtraTreesClassifier(
            n_estimators=params["n_estimators"],
            max_depth=params["max_depth"],
            min_samples_leaf=params["min_samples_leaf"],
            max_features=params["max_features"],
            class_weight=params["class_weight"],
            random_state=SEED,
            n_jobs=-1,
        )

        pipeline = Pipeline(
            steps=[
                (
                    "imputer",
                    SimpleImputer(
                        strategy="median",
                        add_indicator=True,
                    ),
                ),
                (
                    "model",
                    estimator,
                ),
            ]
        )

        return pipeline

    if model_name == "hist_gradient_boosting":

        estimator = HistGradientBoostingClassifier(
            learning_rate=params["learning_rate"],
            max_iter=params["max_iter"],
            max_leaf_nodes=params["max_leaf_nodes"],
            l2_regularization=params["l2_regularization"],
            random_state=SEED,
        )

        pipeline = Pipeline(
            steps=[
                (
                    "imputer",
                    SimpleImputer(
                        strategy="median",
                        add_indicator=True,
                    ),
                ),
                (
                    "model",
                    estimator,
                ),
            ]
        )

        return pipeline

    raise ValueError(
        f"Unknown model: {model_name}"
    )


# ==================================================================================================
# PROTOCOL EXTRACTION
# ==================================================================================================

def get_protocol_data(
    data,
    protocol,
):

    config = PROTOCOLS[protocol]

    train = data[
        (
            data["country"].isin(
                config["train_countries"]
            )
        )
        &
        (
            data["split"] == "train"
        )
    ].copy()

    validation = data[
        (
            data["country"]
            ==
            config["validation_country"]
        )
        &
        (
            data["split"]
            ==
            "validation"
        )
    ].copy()

    test = data[
        (
            data["country"]
            ==
            config["test_country"]
        )
        &
        (
            data["split"]
            ==
            "test"
        )
    ].copy()

    return (
        train,
        validation,
        test,
    )


